// Self-host the web fonts used by the text options, so the page never contacts Google.
//
//   node tools/get-fonts.mjs        (or: npm run fonts)
//
// Downloads the woff2 files from Google Fonts into ./fonts and writes ./fonts/fonts.css. Commit the fonts/ folder.
// index.html loads fonts/fonts.css first and only falls back to Google Fonts when that file is missing.
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export const CSS_URL = 'https://fonts.googleapis.com/css2?family=Montserrat:wght@400;700;800&family=Oswald:wght@400;700&family=Bebas+Neue&family=Playfair+Display:wght@400;700&family=Orbitron:wght@400;700&family=Pacifico&display=swap';
const SUBSETS = new Set(['latin', 'latin-ext']);   // accents and most European languages; the browser only downloads a subset when a character needs it

// Google's CSS is one @font-face per subset, each preceded by a /* subset */ comment.
export function parseFontCss(css) {
  const faces = [];
  for (const m of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)) {
    const prop = n => (m[2].match(new RegExp(n + '\\s*:\\s*([^;]+);')) || [])[1]?.trim();
    const url = (m[2].match(/url\(([^)]+)\)/) || [])[1]?.replace(/['"]/g, '');
    const family = prop('font-family')?.replace(/['"]/g, '');
    if (!SUBSETS.has(m[1]) || !url || !family) continue;
    faces.push({ subset: m[1], family, style: prop('font-style') || 'normal', weight: prop('font-weight') || '400', url, range: prop('unicode-range') });
  }
  return faces;
}

export const fileNameFor = f => f.family.toLowerCase().replace(/\W+/g, '-') + '-' + f.url.split('/').pop().split('?')[0];

export function buildCss(faces) {
  return '/* Generated by tools/get-fonts.mjs: self-hosted copies of the Google Fonts used by the text options. */\n' + faces.map(f =>
    `@font-face {\n  font-family: '${f.family}';\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: url(${fileNameFor(f)}) format('woff2');\n${f.range ? `  unicode-range: ${f.range};\n` : ''}}\n`).join('');
}

async function main() {
  const res = await fetch(CSS_URL, { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36' } });   // a modern UA makes Google answer with woff2
  if (!res.ok) throw new Error(`Google Fonts answered ${res.status}`);
  const faces = parseFontCss(await res.text());
  if (!faces.length) throw new Error('No font faces found in the Google Fonts response.');
  await mkdir(new URL('../fonts/', import.meta.url), { recursive: true });
  const done = new Set();
  for (const f of faces) {
    const name = fileNameFor(f); if (done.has(name)) continue; done.add(name);
    const r = await fetch(f.url); if (!r.ok) throw new Error(`${f.url} answered ${r.status}`);
    await writeFile(new URL('../fonts/' + name, import.meta.url), Buffer.from(await r.arrayBuffer()));
    console.log('saved fonts/' + name);
  }
  await writeFile(new URL('../fonts/fonts.css', import.meta.url), buildCss(faces));
  console.log(`\nDone: ${done.size} files + fonts/fonts.css. Commit the fonts/ folder; the page now loads no third-party fonts.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main().catch(e => { console.error(e.message); process.exit(1); });
